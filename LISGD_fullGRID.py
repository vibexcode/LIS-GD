import numpy as np
import torch
import math

SEEDS = [42, 7, 123, 2024, 31337]
BUDGETS = [500, 2000, 3000, 4000, 5000]   # etkin adim butceleri (LIS-GD icin M = butce + 2)
ETA0 = 0.4          # tepe deger: tuned-const, linear, cosine, triangular, one-cycle icin ortak
ADAMW_LR = 0.003
ADAMW_WD = 0.01

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Kullanilan cihaz:", device)


def load_fashion_mnist():
    try:
        from tensorflow.keras.datasets import fashion_mnist
        (X_train, y_train), (X_test, y_test) = fashion_mnist.load_data()
        X_train = X_train.reshape(len(X_train), -1).astype(np.float32) / 255.0
        X_test = X_test.reshape(len(X_test), -1).astype(np.float32) / 255.0
        return X_train, y_train.astype(np.int64), X_test, y_test.astype(np.int64)
    except Exception:
        from sklearn.datasets import fetch_openml
        from sklearn.model_selection import train_test_split
        d = fetch_openml("Fashion-MNIST", version=1, as_frame=False)
        X = (d.data.astype(np.float32)) / 255.0
        y = d.target.astype(np.int64)
        X_train, X_test, y_train, y_test = train_test_split(
            X, y, test_size=10000, random_state=42, stratify=y)
        return X_train, y_train, X_test, y_test


def he_init(seed, d_in=784, d_hid=64, d_out=10):
    g = torch.Generator(device="cpu").manual_seed(seed)
    W1 = (torch.randn(d_in, d_hid, generator=g) * np.sqrt(2.0 / d_in)).to(device)
    b1 = torch.zeros(d_hid, device=device)
    W2 = (torch.randn(d_hid, d_out, generator=g) * np.sqrt(2.0 / d_hid)).to(device)
    b2 = torch.zeros(d_out, device=device)
    return [W1, b1, W2, b2]


def forward(params, X):
    W1, b1, W2, b2 = params
    Z1 = X @ W1 + b1
    A1 = torch.relu(Z1)
    Z2 = A1 @ W2 + b2
    return Z2, (X, Z1, A1)


def loss_and_grads(params, X, Y_onehot):
    W1, b1, W2, b2 = params
    n = X.shape[0]
    Z2, (X_, Z1, A1) = forward(params, X)
    logP = torch.log_softmax(Z2, dim=1)
    loss = -(Y_onehot * logP).sum(dim=1).mean()
    P = torch.softmax(Z2, dim=1)

    dZ2 = (P - Y_onehot) / n
    dW2 = A1.T @ dZ2
    db2 = dZ2.sum(dim=0)
    dA1 = dZ2 @ W2.T
    dZ1 = dA1 * (Z1 > 0).float()
    dW1 = X.T @ dZ1
    db1 = dZ1.sum(dim=0)
    return loss.item(), [dW1, db1, dW2, db2]


def eval_loss(params, X, Y_onehot):
    with torch.no_grad():
        Z2, _ = forward(params, X)
        logP = torch.log_softmax(Z2, dim=1)
        return (-(Y_onehot * logP).sum(dim=1).mean()).item()


def accuracy(params, X, y):
    Z2, _ = forward(params, X)
    pred = torch.argmax(Z2, dim=1)
    return (pred == y).float().mean().item()


def is_finite_params(params):
    return all(torch.isfinite(p).all().item() for p in params)


def LIS(M):
    k = np.arange(2, M + 1)
    return (np.log(k) / np.log(M) - k / M)[:-1]  # M-2 etkin adim


# ---- LR programlari (t: 0-indeksli adim, T: toplam butce) ----
def lr_const(t, T, eta0=ETA0):
    return eta0


def lr_linear_decay(t, T, eta0=ETA0):
    return eta0 * (1.0 - t / T)


def lr_cosine(t, T, eta0=ETA0):
    return eta0 * 0.5 * (1.0 + math.cos(math.pi * t / T))


def lr_triangular(t, T, eta0=ETA0):
    # tek ucgen dongu: 0 -> eta0 (ilk yari) -> 0 (ikinci yari)
    half = T / 2.0
    if t < half:
        return eta0 * (t / half)
    return eta0 * (1.0 - (t - half) / half)


def lr_onecycle(t, T, eta0=ETA0):
    # ilk %30 eta0/10 -> eta0 (linear warmup), kalan %70 eta0 -> eta0/100 (cosine anneal)
    warmup = 0.3 * T
    if t < warmup:
        return (eta0 / 10.0) + (eta0 - eta0 / 10.0) * (t / warmup)
    frac = (t - warmup) / (T - warmup)
    return (eta0 / 100.0) + 0.5 * (eta0 - eta0 / 100.0) * (1.0 + math.cos(math.pi * frac))


SCHEDULES = {
    "Tuned-const": lr_const,
    "Linear-decay": lr_linear_decay,
    "Cosine": lr_cosine,
    "Triangular-CLR": lr_triangular,
    "One-cycle": lr_onecycle,
}


def run_scheduled_with_checkpoints(X_train, Y_onehot, X_test, Y_test_onehot, y_test,
                                    schedule_fn, seed, checkpoints):
    params = he_init(seed)
    results = {}
    cp_set = set(checkpoints)
    T = max(checkpoints)
    diverged = False
    for it in range(1, T + 1):
        eta_t = schedule_fn(it - 1, T)
        loss, grads = loss_and_grads(params, X_train, Y_onehot)
        with torch.no_grad():
            params = [p - eta_t * g for p, g in zip(params, grads)]
        if not is_finite_params(params):
            diverged = True
            break
        if it in cp_set:
            train_loss = eval_loss(params, X_train, Y_onehot)
            test_loss = eval_loss(params, X_test, Y_test_onehot)
            acc = accuracy(params, X_test, y_test)
            results[it] = (train_loss, test_loss, acc)
    if diverged:
        for cp in checkpoints:
            if cp not in results:
                results[cp] = (None, None, None)
    return results


def run_adamw_with_checkpoints(X_train_np, y_train_np, X_test_np, y_test_np, seed, checkpoints):
    torch.manual_seed(seed)
    g = torch.Generator(device="cpu").manual_seed(seed)
    d_in, d_hid, d_out = 784, 64, 10
    W1 = torch.nn.Parameter((torch.randn(d_in, d_hid, generator=g) * np.sqrt(2.0 / d_in)).to(device))
    b1 = torch.nn.Parameter(torch.zeros(d_hid, device=device))
    W2 = torch.nn.Parameter((torch.randn(d_hid, d_out, generator=g) * np.sqrt(2.0 / d_hid)).to(device))
    b2 = torch.nn.Parameter(torch.zeros(d_out, device=device))
    params = [W1, b1, W2, b2]
    opt = torch.optim.AdamW(params, lr=ADAMW_LR, weight_decay=ADAMW_WD)

    X_train = torch.tensor(X_train_np, device=device)
    y_train = torch.tensor(y_train_np, device=device)
    X_test = torch.tensor(X_test_np, device=device)
    y_test = torch.tensor(y_test_np, device=device)
    Y_onehot = torch.zeros(len(y_train_np), 10, device=device)
    Y_onehot[torch.arange(len(y_train_np)), y_train] = 1.0
    Y_test_onehot = torch.zeros(len(y_test_np), 10, device=device)
    Y_test_onehot[torch.arange(len(y_test_np)), y_test] = 1.0

    def fwd(X):
        Z1 = X @ W1 + b1
        A1 = torch.relu(Z1)
        return A1 @ W2 + b2

    results = {}
    cp_set = set(checkpoints)
    T = max(checkpoints)
    diverged = False
    for it in range(1, T + 1):
        opt.zero_grad()
        Z2 = fwd(X_train)
        logP = torch.log_softmax(Z2, dim=1)
        loss = -(Y_onehot * logP).sum(dim=1).mean()
        loss.backward()
        opt.step()
        if not all(torch.isfinite(p).all().item() for p in params):
            diverged = True
            break
        if it in cp_set:
            with torch.no_grad():
                Ztr = fwd(X_train)
                train_loss = -(Y_onehot * torch.log_softmax(Ztr, dim=1)).sum(dim=1).mean().item()
                Zte = fwd(X_test)
                test_loss = -(Y_test_onehot * torch.log_softmax(Zte, dim=1)).sum(dim=1).mean().item()
                acc = (torch.argmax(Zte, dim=1) == y_test).float().mean().item()
            results[it] = (train_loss, test_loss, acc)
    if diverged:
        for cp in checkpoints:
            if cp not in results:
                results[cp] = (None, None, None)
    return results


def run_lisgd(X_train, Y_onehot, X_test, Y_test_onehot, y_test, M, seed):
    params = he_init(seed)
    for s in LIS(M):
        loss, grads = loss_and_grads(params, X_train, Y_onehot)
        with torch.no_grad():
            params = [p - float(s) * g for p, g in zip(params, grads)]
    train_loss = eval_loss(params, X_train, Y_onehot)
    test_loss = eval_loss(params, X_test, Y_test_onehot)
    return train_loss, test_loss, accuracy(params, X_test, y_test)


def fmt_row(label, vals, n_seeds):
    accs = [a for (tl, xl, a) in vals if a is not None]
    trlosses = [tl for (tl, xl, a) in vals if tl is not None]
    telosses = [xl for (tl, xl, a) in vals if xl is not None]
    div = sum(1 for (tl, xl, a) in vals if a is None)
    if accs:
        return (f"{label:<16}{np.mean(accs)*100:6.2f} +/- {np.std(accs)*100:5.2f}%   "
                f"{np.mean(trlosses):.4f} +/- {np.std(trlosses):.4f}      "
                f"{np.mean(telosses):.4f} +/- {np.std(telosses):.4f}      {div}/{n_seeds}")
    return f"{label:<16}--- hepsi ıraksadı ---                                                    {div}/{n_seeds}"



def run_scheduled_to_budget(X_train, Y_onehot, X_test, Y_test_onehot, y_test,
                            schedule_fn, seed, T_horizon, read_at):
    """Cizelge ufku T_horizon ile kosar, read_at. adimda (train_loss, test_loss, acc) dondurur."""
    params = he_init(seed)
    for it in range(1, read_at + 1):
        eta_t = schedule_fn(it - 1, T_horizon)
        loss, grads = loss_and_grads(params, X_train, Y_onehot)
        with torch.no_grad():
            params = [p - eta_t * g for p, g in zip(params, grads)]
        if not is_finite_params(params):
            return (None, None, None)
    return (eval_loss(params, X_train, Y_onehot),
            eval_loss(params, X_test, Y_test_onehot),
            accuracy(params, X_test, y_test))


